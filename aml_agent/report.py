"""Render a case as a Markdown report suitable for the case management file."""
from __future__ import annotations

from .agent import CaseResult


def render_case_report(r: CaseResult) -> str:
    d = r.decision
    lines = [
        f"# Case report: {r.alert_id}",
        "",
        f"- **Customer:** {r.customer_name} ({r.customer_id})",
        f"- **Run ID:** {r.run_id}  |  **Investigator:** {r.mode} ({r.model})  |  "
        f"**Prompt:** {r.audit.prompt_version}  |  **Data version:** {r.audit.data_version}",
        f"- **Status:** {r.status}",
        "",
        "## Recommendation",
        "",
        f"**{d['disposition']}**, risk score {d['risk_score']}/100, confidence {d['confidence']}.",
        f"Independent rules engine: {r.rules['disposition']} (score {r.rules['score']}).",
        "",
    ]
    if r.controls:
        lines += ["## Controls", ""] + [f"- `{c['control']}` ({c['severity']}): {c['message']}" for c in r.controls] + [""]
    lines += ["## Key findings", ""]
    lines += [f"- {kf['finding']} _Evidence: {', '.join(kf['evidence']) or 'none'}_" for kf in d["key_findings"]] or ["- None"]
    lines += ["", "## Mitigating factors", ""]
    lines += [f"- {m['factor']} _Evidence: {', '.join(m['evidence']) or 'none'}_" for m in d["mitigating_factors"]] or ["- None"]
    lines += ["", "## Narrative", "", d["narrative"], "", "## Recommended actions", ""]
    lines += [f"- {a}" for a in d["recommended_actions"]]
    lines += ["", f"**Policy references:** {', '.join(d['policy_refs']) or 'none'}", ""]
    if r.analyst_decision:
        a = r.analyst_decision
        lines += ["## Analyst decision", "",
                  f"- **{a['action']}** by {a['analyst']} at {a['decided_at']}: final disposition "
                  f"**{a['final_disposition']}** (agent recommended {a['agent_recommendation']})."]
        if a.get("reason"):
            lines.append(f"- Reason: {a['reason']}")
        if a.get("narrative_edited"):
            lines += ["", "### Final narrative (edited by analyst)", "", a["final_narrative"]]
        lines.append("")
    lines += ["## Audit trail", "", "| # | Elapsed (ms) | Actor | Action | Summary |", "|---|---|---|---|---|"]
    for e in r.audit.events:
        det = e["detail"]
        if isinstance(det, dict):
            summary = det.get("summary") or det.get("message") or ", ".join(
                f"{k}={v}" for k, v in det.items() if k not in {"output", "drivers", "calls"} and v is not None)
        else:
            summary = det or ""
        summary = str(summary).replace("|", "/").replace("\n", " ")[:160]
        lines.append(f"| {e['seq']} | {e['elapsed_ms']} | {e['actor']} | {e['action']} | {summary} |")
    lines += ["", "_Synthetic data. Generated by the AML Alert Triage Agent demo; not a real case._", ""]
    return "\n".join(lines)
